const assert = require('node:assert/strict');
const fs = require('node:fs');
const crypto = require('node:crypto');
const vm = require('node:vm');
const read = path => JSON.parse(fs.readFileSync(path, 'utf8'));
const file = 'undergraduate/Simon-Marais-problems.json';
const data = read(file);
const papers = read('metadata/smmc-official-papers.json').papers;
const checks = read('metadata/smmc-statement-checks.json').collections[file].statement_checks;
const html = fs.readFileSync('index.html', 'utf8');
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
assert.equal(data.problem_count, 88);
assert.equal(data.paper_count, 22);
assert.deepEqual(data.years.map(y => y.year), Array.from({length:9}, (_, i) => 2017+i));
assert.equal(papers.length, 22);
const all = [];
for (const y of data.years) {
  const letters = y.year <= 2021 ? ['A','B'] : ['A','B','C'];
  assert.equal(y.problems.length, 4*letters.length);
  assert.deepEqual([...new Set(y.problems.map(p => p.paper))], letters);
  for (const paper of letters) assert.deepEqual(y.problems.filter(p => p.paper===paper).map(p => p.number), [1,2,3,4]);
  for (const p of y.problems) {
    const uid = `smmc.${y.year}.${p.paper_id}.${p.number}`;
    const source = papers.find(d => d.year === y.year && d.paper === p.paper);
    assert.ok(source, uid);
    assert.equal(p.paper_id, p.paper.charCodeAt(0)-64);
    assert.equal(p.paper_label, (y.year <= 2021 ? 'Session ' : 'Paper ')+p.paper);
    assert.equal(p.source_problem_number, p.paper+p.number);
    assert.ok(!('day' in p) && !('statement_asset' in p), uid);
    assert.equal(p.statement_format, 'english_text_latex');
    assert.equal(p.statement_verified, true);
    assert.equal(p.text_transcription_verified, true);
    assert.deepEqual(p.review_flags, []);
    assert.equal(p.verification_page, 2);
    assert.equal(p.source_url, source.source_url);
    assert.equal(p.source_document_sha256, source.sha256);
    assert.match(source.sha256, /^[0-9a-f]{64}$/);
    assert.match(source.source_url, /^https:\/\/www\.simonmarais\.org\/uploads\/.*\.pdf$/);
    assert.equal(hash(p.problem), p.statement_sha256, uid);
    assert.equal(checks[uid].reviewed_statement, p.problem);
    assert.equal(checks[uid].statement_sha256, p.statement_sha256);
    assert.equal((p.problem.match(/\$/g)||[]).length % 2, 0, uid);
    assert.doesNotMatch(p.problem, /[\u0370-\u03ff\u1f00-\u1fff\x00-\x08\x0b\x0c\x0e-\x1f]/);
    assert.ok(p.problem.length >= 80);
    assert.deepEqual(p.topics, [p.category]);
    assert.ok(['Algebra','Geometry','Combinatorics','Number Theory'].includes(p.category));
    assert.deepEqual(p.problem_dna, []); // Technique classification is not inferred from titles.
    assert.ok(!('solution' in p));
    if(p.paper==='B' && p.number===4) assert.match(p.historical_open_problem_note, /does not assert the present research status/);
    all.push({year:y.year,...p});
  }
}
const get = (y, paper, n) => all.find(p => p.year===y && p.paper===paper && p.number===n);
// Guard formulas that plain PDF extraction corrupts or loses.
assert.ok(get(2017,'A',2).problem.includes('2017^{2017}'));
assert.ok(get(2017,'A',4).problem.includes('k\\frac{\\overrightarrow{PA_k}}{\\|\\overrightarrow{PA_k}\\|^5}'));
assert.ok(get(2018,'B',3).problem.includes('speed $\\frac{1}{2018}$'));
assert.ok(get(2019,'B',1).problem.includes('e^{\\cos x}(380-x-x^2)'));
assert.ok(get(2021,'A',2).problem.includes('(n+1-\\gcd(a_n,n))\\times a_n'));
assert.ok(get(2022,'A',2).problem.includes('2^n') && get(2022,'A',2).problem.includes('\\frac{1}{e^2}'));
assert.ok(get(2022,'A',3).problem.includes('\\pi\\sin\\frac{\\pi t}{2}'));
assert.ok(get(2022,'C',1).problem.includes('\\min\\left\\{x,\\frac{A}{y},y+\\frac{B}{x}'));
assert.ok(get(2023,'C',4).problem.includes('n>\\frac{k}{2023}'));
assert.ok(get(2024,'A',1).problem.includes('\\lfloor a\\rfloor b='));
assert.ok(get(2024,'C',2).problem.includes('\\frac72x-\\frac12'));
assert.ok(get(2025,'C',1).problem.includes('$2i-1$'));
const figure = get(2023,'A',1);
assert.equal(all.filter(p=>p.figure_asset).length, 1);
assert.equal(hash(fs.readFileSync(figure.figure_asset)), figure.figure_sha256);
assert.deepEqual(figure.figure_crop_points, [90,260,510,390]);
assert.ok(figure.problem.includes(figure.figure_asset));
assert.match(figure.figure_provenance, /Diagram-only/);
assert.match(html, /key: 'smmc'.*scope: 'undergraduate'/);
assert.match(html, /c\.key === 'smmc' \? 88/);
const ctx = {};
vm.createContext(ctx);
vm.runInContext(html.slice(html.indexOf('function textHash('), html.indexOf('function loadCountry(')),ctx);
const normalized=ctx.normalizeYears({key:'smmc'},data);
assert.equal(new Set(normalized.map(p=>p.uid)).size,88);
assert.equal(normalized.filter(p=>p.day===3).length,16);
assert.ok(normalized.every(p=>!p.statementAsset && p.paperLabel));
const manifest=read('metadata/runtime/manifest.json').files[file];
assert.equal(manifest.total,88);
assert.deepEqual(Object.values(manifest.years),[8,8,8,8,8,12,12,12,12]);
console.log('Simon Marais: 88 native statements, 22 official papers, paper identities, critical formulas and diagram validated.');
